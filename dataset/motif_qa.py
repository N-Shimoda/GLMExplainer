from typing import Callable, Optional, Union

import matplotlib.pyplot as plt
import networkx as nx
import torch
from torch_geometric.data import Data, InMemoryDataset
from torch_geometric.datasets import ExplainerDataset
from torch_geometric.datasets.graph_generator import (  # noqa E401
    BAGraph,
    ERGraph,
    GridGraph,
    TreeGraph,
)
from torch_geometric.explain import Explanation
from torch_geometric.utils import is_undirected, to_networkx

_NAME2GEN = {
    "bagraph": BAGraph,
    "ba": BAGraph,
    "ergraph": ERGraph,
    "er": ERGraph,
    "gridgraph": GridGraph,
    "grid": GridGraph,
    "treegraph": TreeGraph,
    "tree": TreeGraph,
}


class NegativeGraphs(InMemoryDataset):
    """Dataset that produces base graphs without motifs.

    This dataset yields graphs generated by the provided graph generator and
    decorates them with zero-valued masks and the ``has_motif`` label set to 0.
    """

    def __init__(
        self,
        graph_generator: Union[str, Callable[[], Data], object],
        num_graphs: int,
        graph_generator_kwargs: Optional[dict] = None,
        seed: Optional[int] = None,
    ):
        """Initialize the negative graph dataset.

        Parameters
        ----------
        graph_generator : Union[str, Callable[[], Data], object]
            Descriptor of the graph generator. Accepts a string alias,
            a callable object, or an initialized generator instance.
        num_graphs : int
            Number of graphs the dataset should produce.
        graph_generator_kwargs : dict, optional
            Keyword arguments passed to the graph generator during construction.
        seed : int, optional
            Random seed for deterministic graph generation.
        """
        self.num_graphs = int(num_graphs)
        self.graph_generator_kwargs = graph_generator_kwargs or {}

        # Configure deterministic seed when provided.
        if seed is not None:
            torch.manual_seed(seed)

        # Resolve graph generator descriptor to a callable.
        self.gen = self._resolve_graph_generator(graph_generator, self.graph_generator_kwargs)

        if not callable(self.gen):
            raise TypeError("graph_generator must be a callable that returns a PyG Data object.")

    def _resolve_graph_generator(self, gg, kwargs):
        """Resolve the graph generator descriptor into a callable.

        Parameters
        ----------
        gg : Union[str, Callable, type]
            Generator descriptor such as a string alias, initialized object,
            callable, or class.
        kwargs : dict
            Keyword arguments forwarded to the generator on construction.

        Returns
        -------
        Callable
            Callable object that returns a ``torch_geometric.data.Data`` instance.

        Raises
        ------
        ValueError
            If a string alias is provided that does not map to a known generator.
        TypeError
            If the descriptor cannot be resolved into a callable generator.
        """
        # 1) Resolve string alias to a graph generator instance.
        if isinstance(gg, str):
            key = gg.lower()
            if key not in _NAME2GEN or _NAME2GEN[key] is None:
                raise ValueError(f"Unknown graph_generator string: {gg!r}")
            return _NAME2GEN[key](**kwargs)

        # 2) Use initialized instances or simple callables directly.
        if callable(getattr(gg, "__call__", None)):
            return gg  # Already initialized instance or function.

        # 3) Instantiate generator classes using provided kwargs.
        if isinstance(gg, type):
            return gg(**kwargs)

        raise TypeError("graph_generator must be str / initialized generator / class / callable.")

    def __len__(self):
        """Return the number of graphs in the dataset.

        Returns
        -------
        int
            Number of graphs to generate.
        """
        return self.num_graphs

    def __getitem__(self, idx):
        """Generate a single negative graph sample.

        Parameters
        ----------
        idx : int
            Index of the requested sample. Ignored because graphs are generated on demand.

        Returns
        -------
        Data
            Graph with zero-valued node and edge masks and ``has_motif`` set to 0.
        """
        # Generate a base graph instance.
        base: Data = self.gen()  # PyG GraphGenerator returns Data via __call__.

        # Match device and dtype to the edge index (CPU assumed by default).
        device = base.edge_index.device
        num_nodes = base.num_nodes
        # Determine number of edges from the edge_index column count.
        num_edges = base.edge_index.size(1)

        # Attach zero masks since negative graphs contain no motifs.
        base.node_mask = torch.zeros(num_nodes, dtype=torch.float32, device=device)
        base.edge_mask = torch.zeros(num_edges, dtype=torch.float32, device=device)

        # Label the graph to indicate absence of motifs.
        base.has_motif = torch.tensor(0, dtype=torch.long)

        # Optionally add node labels for compatibility.
        # base.y = torch.zeros(num_nodes, dtype=torch.long, device=device)

        return base


def create_base_graphs(num_pos_samples: int, num_neg_samples: int):

    graph_gen = BAGraph(num_nodes=20, num_edges=2)
    ds0 = ExplainerDataset(
        graph_generator=graph_gen,
        motif_generator="house",
        num_motifs=1,
        num_graphs=num_pos_samples,
    )
    ds1 = NegativeGraphs(
        graph_generator=graph_gen,
        num_graphs=num_neg_samples,
    )

    return ds0, ds1


def visualize_graph(data: Explanation, filename: str):

    if not is_undirected(data.edge_index):
        raise ValueError("The generated graph is not undirected.")
    G = to_networkx(data, to_undirected=True)

    # Setup layout
    pos = nx.spring_layout(G, seed=42)

    # Extract motif nodes from node_mask
    node_mask = getattr(data, "node_mask", None)
    print(node_mask)
    motif_nodes = node_mask.nonzero(as_tuple=True)[0].tolist()
    normal_nodes = [n for n in G.nodes if n not in motif_nodes]
    print(f"Motif nodes: {motif_nodes}")

    # Draw figure
    plt.figure(figsize=(6, 6))
    nx.draw_networkx_nodes(G, pos, nodelist=normal_nodes, node_color="skyblue", node_size=40)
    nx.draw_networkx_nodes(G, pos, nodelist=motif_nodes, node_color="orange", node_size=80)
    nx.draw_networkx_edges(G, pos, alpha=0.3)

    # Draw node labels (indices). Use black for normal nodes and white for motif nodes
    # so labels remain readable on the different node colors.
    labels = {n: str(n) for n in G.nodes()}
    if normal_nodes:
        nx.draw_networkx_labels(G, pos, labels={n: labels[n] for n in normal_nodes}, font_size=8, font_color="black")
    if motif_nodes:
        nx.draw_networkx_labels(G, pos, labels={n: labels[n] for n in motif_nodes}, font_size=8, font_color="white")

    plt.title("Graph with Motifs Highlighted")
    plt.axis("off")
    plt.savefig(filename, bbox_inches="tight", dpi=300)
    plt.close()


if __name__ == "__main__":
    ds0, ds1 = create_base_graphs(num_pos_samples=100, num_neg_samples=100)
    print("Positive dataset:", ds0, len(ds0))
    for i in range(3):
        visualize_graph(ds0[i], filename=f"dataset/pos_graph_{i}.png")

    print("Negative dataset:", ds1, len(ds1))
    for i in range(3):
        visualize_graph(ds1[i], filename=f"dataset/neg_graph_{i}.png")
